# (this file is named unittest.py and would otherwise shadow the stdlib module).
_spec = importlib.util.spec_from_file_location("harness_lib", os.path.join(HERE, "harness_lib.py"))
h = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(h)

sys.path = [p for p in sys.path if os.path.abspath(p or ".") != HERE]

import torch  # noqa: E402

with open(os.path.join(HERE, "meta.json")) as _fh:
    META = json.load(_fh)

REGIME = META["regime"]
GEO = META["geometry"]
TOL = float(META.get("tol", 2e-2))
DEV = "cuda" if torch.cuda.is_available() else "cpu"

E = int(GEO["num_experts"])             # 896 (per-rank expert count)
TOPK = int(GEO["topk"])                 # 16
MODEL_DIM = int(GEO["model_dim"])       # 3584 (routed-expert output dim)
INTER_DIM = int(GEO["inter_dim"])       # 384  (= moe_intermediate / TP8)


# --------------------------------------------------------------------------- kernel binding

