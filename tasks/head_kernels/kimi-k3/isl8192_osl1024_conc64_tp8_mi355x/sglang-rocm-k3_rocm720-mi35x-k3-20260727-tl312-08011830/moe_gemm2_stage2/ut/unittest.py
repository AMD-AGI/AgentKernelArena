#!/usr/bin/env python3
"""IMMUTABLE unittest for the aiter FlyDSL fused MoE stage-2 op (Kimi-K3, TP=8, gfx950).

OP (the whole rebindable fused seam -- BOTH hot kernels run inside this ONE call):
    aiter.ops.flydsl.moe_kernels:flydsl_moe_stage2
      -> mfma_moe2_afp8_wfp4_bf16_cshuffle_t64x256x128_..._acc0   (down-proj GEMM)  ~7.1% GPU time
      -> moe_reduction_kernel_plain_bf16_topk16_md3584            (top-16 combine)  ~3.2% GPU time
    live seam: AiterRunnerCore.run -> aiter.fused_moe:fused_moe -> _flydsl_stage2_wrapper
               -> aiter.ops.flydsl.flydsl_moe_stage2
    The byte-reduction lever (fusing the top-16 reduction into the cshuffle epilogue) is entirely
    inside this call, so the call -- not a single kernel -- is the timed unit.

BASELINE  = the FROZEN production package copy in baseline_src/flydsl/ (never kernel_src/).
CANDIDATE = whatever is currently in kernel_src/flydsl/.
speedup   = baseline_ms / candidate_ms, in ANY language/backend (flydsl, aiter, triton, ...).

ROUTING IS REAL: sorted_token_ids / sorted_expert_ids / num_valid_ids / sorted_weights / topk_ids in
reference_io.pt were captured from the LIVE TP=8 server on the served workload (or rebuilt from the
LIVE topk_ids with the real aiter moe_sorting); it is never synthesized. The value-INDEPENDENT heavy
operands (fp8 activations, packed mxfp4 w2 + scales) are re-synthesized deterministically at the
captured dims/dtypes, and the golden output is the frozen baseline's own output on them.

DO NOT EDIT THIS FILE, harness_lib.py, reference_io.pt, meta.json or baseline_src/ during optimization.
"""
