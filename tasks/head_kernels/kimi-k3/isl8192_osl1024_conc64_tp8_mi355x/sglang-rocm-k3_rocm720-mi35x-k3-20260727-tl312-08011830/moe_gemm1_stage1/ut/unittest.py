# THE KERNEL IS NOT RUN-TO-RUN REPRODUCIBLE. Measured on gfx950 with the live launch variant, and
# reproduced identically through the INSTALLED aiter and through aiter's OWN a16w4 data recipe
# (shuffle_weight_a16w4 / shuffle_scale_a16w4): once the sorted routing spans more than ~50 expert
# blocks, a single launch disagrees with the next on ~0.5-1% of elements (relL2 ~2e-2). Ruled out as
# causes: operand OOB (guard-padded a / w1 / w1_scale), output OOB (a guard row after `out` stays
# exactly zero, so stores ARE masked), the padding marker ((topk<<24)|M, no aliasing, no duplicate
# (token,slot) pairs), every launch knob (k_wave / k_batch / xcd_swizzle / waves_per_eu / b_nt /
# use_async_copy), the call convention (identical to _flydsl_stage1_wrapper), and the machine
# (ut_stage2's UT passes on this node). aiter's own op_test for this path gates it statistically
# (cosine similarity, atol=1.0, pass_pct=95) rather than elementwise, for the same reason.
#
# The disagreement is a MINORITY-VOTE artifact: every element has a stable majority value with
# occasional outliers, so an elementwise median over MEDIAN_LAUNCHES independent launches recovers
# the deterministic result BITWISE (measured: 0/4 unstable trials at K=21 for all three buckets,
# vs 1/4 at K=9 for decode_M64). Correctness therefore compares medians -- which keeps the ordinary
# elementwise tolerance gate meaningful (a real math error still fails at tol=0.02 by 25-450x:
# act=silu -> err 8.9, situ_beta=0.5 -> err 0.50) instead of forcing a tolerance so loose it gates
# nothing. TIMING still measures a SINGLE launch, because that is what the server pays.
MEDIAN_LAUNCHES = int(META.get("median_launches", 21))

E = int(GEO["num_experts"])             # 896 (per-rank expert count)
TOPK = int(GEO["topk"])                 # 16
MODEL_DIM = int(GEO["model_dim"])       # 3584 (hidden size = GEMM K)
INTER_DIM = int(GEO["inter_dim"])       # 384  (= moe_intermediate / TP8; GEMM N is 2*INTER_DIM)


