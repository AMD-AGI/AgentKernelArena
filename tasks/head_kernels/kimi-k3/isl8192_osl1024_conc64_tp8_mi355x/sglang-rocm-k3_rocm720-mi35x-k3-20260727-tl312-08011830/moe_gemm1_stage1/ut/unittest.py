#!/usr/bin/env python3
"""IMMUTABLE unittest for the aiter FlyDSL fused MoE stage-1 op (Kimi-K3, TP=8, gfx950).

OP (the rebindable fused seam):
    aiter.ops.flydsl.moe_kernels:flydsl_moe_stage1
      -> flydsl_moe1_abf16_wfp4_bf16_t32x64x256_w3_xcd4_kw2   (gate/up GEMM + SiTUv2 epilogue)
    profiled as `moe_gemm1_0` -- 13.53% of e2e-weighted GPU time, the single largest kernel in the
    Kimi-K3 0828 profile (99176 calls / 10624.8 ms; prefill 956.7 us/call, decode 62.3 us/call).
    live seam: AiterRunnerCore.run -> aiter.fused_moe:fused_moe -> fused_moe_2stages
               -> _flydsl_stage1_wrapper (fused_moe.py:1169) -> aiter.ops.flydsl.flydsl_moe_stage1

    The gate/up GEMM, the SiTUv2 activation and the gate*up multiply all live inside this ONE call,
    so the call -- not a single kernel -- is the timed unit. In the 0828 configuration out_dtype is
    'bf16', i.e. stage-1 does NOT fuse the output requant: the call returns one bf16
    [token_num, topk, inter_dim] tensor and the mxfp4 quantization of a2 happens in a separate
    fused_dynamic_mxfp4_quant_moe_sort call outside this seam.

BASELINE  = the FROZEN production package copy in baseline_src/flydsl/ (never kernel_src/).
CANDIDATE = whatever is currently in kernel_src/flydsl/.
speedup   = baseline_ms / candidate_ms, in ANY language/backend (flydsl, aiter, triton, ...).

ROUTING IS REAL: sorted_token_ids / sorted_expert_ids / num_valid_ids in reference_io.pt come from
the SERVED topk distribution of the live TP=8 run (captured at the stage-2 seam of the 0817 session,
inverted back to dense topk_ids/weights and re-sorted by the production aiter moe_sorting at this
stage's own block size) -- it is never synthesized, because the routing skew IS this op's cost
signal. See README.md / meta.routing_provenance for the exact chain and its limits. The
value-INDEPENDENT heavy operands (bf16 hidden states, packed mxfp4 w1 + e8m0 scales) are
re-synthesized deterministically at the live dims/dtypes, and the golden output is the frozen
baseline's own output on them.

DO NOT EDIT THIS FILE, harness_lib.py, reference_io.pt, meta.json or baseline_src/ during optimization.
"""
