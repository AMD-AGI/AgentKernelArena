"""arena-eval-v1 actions of a SIKL v5 schema task, judged by `python -m sikl validate` at the pinned SIKL commit.

Standard library only; run as `python3 -I -B`. Generated by agents/sikl_task_builder; it imports nothing from
Arena or the builder.
"""
import atexit
import contextlib
import functools
import hashlib
import json
import os
import re
import shutil
import statistics
import subprocess
import sys
import tempfile
from importlib import metadata
from pathlib import Path

SIKL_ROOT = Path(os.environ.get("AKA_SIKL_ROOT", "/opt/sikl")).resolve()
CK = "3rdparty/composable_kernel"
# Shared across validations as in SIKL CI; every other kernel cache is private to one validation.
AITER_JIT_DIR = "/tmp/aka-sikl-aiter-jit"
# SIKL's code-lint check-added-large-files limit (default maxkb=500).
MAX_SCHEMA_BYTES = 500 * 1024
REPORT_VERSION = 2
# Findings of a correct kernel that is merely slow: they decide performance, never correctness.
SLOW_BUT_CORRECT_CODES = ("not_faster", "regressed")
COMPILE_CODES = ("build_failed", "schema_invalid", "kernel_missing")
LOG_TAIL_CHARS = 4000
# SIKL retries a tracer fault in a fresh process, but a bench runner killed by a signal mid-measurement is a
# candidate_crash with no retry; validate reruns once when every failure is one of these.
SIGNAL_CRASH = re.compile(r"exited with code -\d+$")
# Untracked non-schema file in the private checkout: with it, a path already at the base is still benched,
# and the base exempts that shipped kernel from the source rules, as a SIKL PR that also changes code would.
BASE_MARKER = ".sikl-task-base"
TRITON_PIN = re.compile(r"--force-reinstall 'triton==([0-9.]+)'")
FLYDSL_PIN = re.compile(r'^FLYDSL_VERSION = "flydsl==([^"]+)"$', re.M)
ROLES = ("baseline", "candidate")
ACTIONS = ("compile", "correctness", "performance")
# Run with cwd = the private checkout: `-c` puts cwd first on sys.path, a script file would not.
GENERATE = """
import json, sys
from pathlib import Path
from sikl.core.contract.expr import json_file_text
workspace, out = Path(sys.argv[1]), Path(sys.argv[2])
schema = json.loads((workspace / "start.json").read_text(encoding="utf-8"))
for source in schema["kernel"]["sources"]:
    source["content"] = (workspace / "source" / source["path"]).read_text(encoding="utf-8")
for workload in schema["workloads"]:
    workload.pop("speedup", None)
    workload.pop("accuracy", None)
out.write_text(json_file_text(schema), encoding="utf-8")
"""


class Failed(Exception):
    """The action fails for this reason."""


def tail(text: str) -> str:
    return text[-LOG_TAIL_CHARS:]


@functools.cache
def git_config() -> str:
    # The runner's own global config, never the agent's: a local clone runs upload-pack on the source's git
    # dir with GIT_CONFIG_PARAMETERS cleared, so `-c safe.directory` would not reach it.
    fd, path = tempfile.mkstemp(prefix="sikl-gitconfig-")
    with os.fdopen(fd, "w") as f:
        f.write("[core]\n\thooksPath = /dev/null\n[safe]\n")
        f.writelines(f"\tdirectory = {p}\n" for p in (SIKL_ROOT, SIKL_ROOT / ".git", SIKL_ROOT / CK))
    atexit.register(os.unlink, path)
    return path


def git(cwd, *args: str) -> str:
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    env.update(GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_SYSTEM=os.devnull, GIT_CONFIG_GLOBAL=git_config(),
               GIT_TERMINAL_PROMPT="0")
    return subprocess.run(["git", "-c", "core.hooksPath=/dev/null", "-c", f"safe.directory={Path(cwd).resolve()}",
                           "-C", str(cwd), *args], env=env, capture_output=True, text=True, check=True).stdout


def axes_text(axes: dict) -> str:
    return ",".join(f"{a}={v}" for a, v in axes.items())


def read_json(workspace: Path, relative: str) -> dict:
    return json.loads((workspace / relative).read_text(encoding="utf-8"))


def case_ids(start: dict) -> list[str]:
    return [axes_text(w["axes"]) for w in start["workloads"]]


def schema_dir(start: dict) -> str:
    return f"sikl/ops/{start['op_type']}/impls/{start['kernel']['language']}/{start['name']}"


def content_hash(workspace: Path, role: str) -> str:
    h = hashlib.sha256()
    for source in read_json(workspace, "start.json")["kernel"]["sources"]:
        if role == "baseline":
            data = source["content"].encode()
        else:
            data = (workspace / "source" / source["path"]).read_bytes()
        h.update(source["path"].encode() + b"\0" + data + b"\0")
    return h.hexdigest()[:16]


def report_dir(workspace: Path, role: str) -> Path:
    return workspace / "reports" / f"{role}-{content_hash(workspace, role)}"


def stage(report: dict, name: str) -> dict | None:
    return next((s for s in report["stages"] if s["stage_name"] == name), None)


@contextlib.contextmanager
def private_checkout(commit: str):
    # Resolved: SIKL prints resolved paths, and the candidate's export check line is matched on it.
    tmp = Path(tempfile.mkdtemp(prefix="sikl-")).resolve()
    try:
        checkout = tmp / "SIKL"
        git(tmp, "clone", "-q", "--shared", "--no-checkout", str(SIKL_ROOT), str(checkout))
        git(checkout, "checkout", "-q", "--detach", commit)
        for name in ("tmp", "home"):
            (tmp / name).mkdir()
        yield checkout
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def sikl_env(checkout: Path, arch: str) -> dict:
    tmp = checkout.parent / "tmp"
    env = {k: v for k, v in os.environ.items() if k != "AITER_ASM_DIR" and not k.startswith("GIT_")}
    env.update(
        PYTHONPATH=str(checkout),
        PYTHONNOUSERSITE="1",
        PYTHONDONTWRITEBYTECODE="1",
        HOME=str(checkout.parent / "home"),
        GPU_ARCHS=arch,
        CK_DIR=str(SIKL_ROOT / CK),
        AITER_JIT_DIR=AITER_JIT_DIR,
        TMPDIR=str(tmp),
        FLYDSL_RUNTIME_CACHE_DIR=str(tmp / "flydsl-runtime"),
        FLYDSL_AUTOTUNE_CACHE_DIR=str(tmp / "flydsl-autotune"),
        TRITON_CACHE_DIR=str(tmp / "triton"),
        XDG_CACHE_HOME=str(tmp / "xdg"),
        SIKL_KERNEL_CACHE_DIR=str(tmp / "sikl-kernels"),
    )
    return env


def sikl(checkout: Path, env: dict, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, "-s", "-m", "sikl", *args], cwd=checkout, env=env,
                          capture_output=True, text=True)


def build_candidate(checkout: Path, env: dict, workspace: Path, start: dict, reports: Path) -> tuple[str, bool]:
    """Write the candidate into the checkout; return its repo path and whether it is new at the base."""
    out = checkout / schema_dir(start) / "candidate.json"
    p = subprocess.run([sys.executable, "-s", "-c", GENERATE, str(workspace), str(out)], cwd=checkout,
                       env=env, capture_output=True, text=True)
    if p.returncode:
        raise Failed("cannot build the candidate schema: " + tail(p.stderr))
    size = out.stat().st_size
    if size > MAX_SCHEMA_BYTES:
        raise Failed(f"candidate schema is {size} bytes, over the {MAX_SCHEMA_BYTES}-byte limit of SIKL code-lint")
    p = sikl(checkout, env, "export", "check")
    moved = f"{out}: not at <ops>/"
    mine = [line for line in p.stderr.splitlines() if line.startswith(f"{out}: ")]
    if len(mine) != 1 or not mine[0].startswith(moved):
        raise Failed("export check: " + ("\n".join(mine) or tail(p.stderr)))
    path = "sikl/ops/" + mine[0][len(moved):]
    if git(checkout, "ls-tree", "HEAD", "--", path).strip():
        out.unlink()
        return path, False
    os.rename(out, checkout / path)
    p = sikl(checkout, env, "export", "check")
    if p.returncode:
        raise Failed("export check after rename: " + tail(p.stderr))
    (reports / path).parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(checkout / path, reports / path)
    return path, True


def ensure_report(workspace: Path, role: str, start: dict, fresh: bool) -> Path:
    reports = report_dir(workspace, role)
    if reports.is_symlink():
        reports.unlink()
    if fresh:
        shutil.rmtree(reports, ignore_errors=True)
    elif (reports / "exit_code").exists():
        return reports
    provenance = read_json(workspace, "scripts/provenance.json")
    commit = provenance["sikl_commit"]
    with private_checkout(commit) as checkout:
        env = sikl_env(checkout, provenance["arch"])
        reports.mkdir(parents=True, exist_ok=True)
        if role == "baseline":
            # validate-task checked that start.json is this committed blob.
            path, is_new = provenance["schema_path"], False
        else:
            path, is_new = build_candidate(checkout, env, workspace, start, reports)
        if not is_new:
            (checkout / BASE_MARKER).write_text("")
        argv = ["validate", path, "--base", commit, "--stages", "audit,bench", "--devices", "0",
                "--out", str(reports)]
        log = ""
        for attempt in (1, 2):
            (reports / "report.json").unlink(missing_ok=True)
            p = sikl(checkout, env, *argv)
            log += p.stdout + p.stderr
            (reports / "validate.log").write_text(log, encoding="utf-8")
            if not (reports / "report.json").is_file():
                raise Failed(f"validate wrote no report (rc {p.returncode}): " + tail(p.stdout + p.stderr))
            if attempt == 2 or not platform_flake(json.loads((reports / "report.json").read_text())):
                break
        # Written last: its presence marks a complete report, the cache hit test above.
        (reports / "exit_code").write_text(f"{p.returncode}\n")
    return reports


def platform_flake(report: dict) -> bool:
    bad = [f for s in report["stages"] for f in s["findings"] if f["code"] not in SLOW_BUT_CORRECT_CODES]
    return bool(bad) and all(f["code"] == "platform_failure"
                             or (f["code"] == "candidate_crash" and SIGNAL_CRASH.search(f["detail"])) for f in bad)


def finding_line(f: dict) -> str:
    return f"{f['code']} {axes_text(f['axes']) if f['axes'] else '-'}: {f['detail']}"


def aborted_reason(report: dict) -> str:
    deciding = next((s for status in ("failed", "aborted") for s in report["stages"] if s["status"] == status), None)
    if deciding is None:  # validate killed after writing a passed report.json
        return "validation aborted"
    return f"validation {deciding['status']} ({deciding['stage_name']}): {deciding['detail']}"


def correctness(ids: list[str], findings: list, report: dict, exit_code: int) -> tuple[str, list, str | None]:
    bad = [f for f in findings if f["code"] not in SLOW_BUT_CORRECT_CODES]
    if exit_code == 0 or (exit_code == 1 and findings and not bad):
        return "PASS", [{"test_case_id": i, "status": "PASS"} for i in ids], None
    aborted = exit_code not in (0, 1)
    everyone = aborted or not bad or any(f["axes"] is None for f in bad)
    located = {axes_text(f["axes"]) for f in bad if f["axes"] is not None}
    cases = [{"test_case_id": i, "status": "FAIL" if everyone or i in located else "PASS"} for i in ids]
    if aborted:
        reason = aborted_reason(report)
    else:
        reason = "\n".join(finding_line(f) for f in bad) or f"validate exit code {exit_code} without findings"
    return "FAIL", cases, reason


def judge(action: str, start: dict, report: dict, exit_code: int) -> tuple[str, list, str | None]:
    if report.get("version") != REPORT_VERSION:
        raise Failed(f"unsupported SIKL report version {report.get('version')!r}")
    ids = case_ids(start)
    findings = [f for s in report["stages"] for f in s["findings"]]
    if action == "compile":
        if exit_code not in (0, 1):
            return "FAIL", [], aborted_reason(report)
        build = [f for f in findings if f["code"] in COMPILE_CODES
                 or (f["code"] == "source_rejected" and f["detail"].startswith("SA0 "))]
        if build:
            return "FAIL", [], "\n".join(finding_line(f) for f in build)
        return "PASS", [], None
    status, cases, reason = correctness(ids, findings, report, exit_code)
    if action == "correctness" or status == "FAIL":
        return status, cases, reason
    bench = stage(report, "bench")
    records = bench.get("workload_records", []) if bench else []
    cases, untimed = [], []
    for workload in start["workloads"]:
        case_id = axes_text(workload["axes"])
        record = next((r for r in records if r["axes"] == workload["axes"]), None)
        timing = next((t for t in (record["timings"] if record else []) if t["versus"] == "baseline"), None)
        if timing and timing["candidate_milliseconds"]:
            cases.append({"test_case_id": case_id, "status": "PASS", "benchmark_method": "cuda_graph",
                          "execution_time_ms": statistics.median(timing["candidate_milliseconds"])})
        else:
            cases.append({"test_case_id": case_id, "status": "FAIL"})
            untimed.append(case_id)
    if untimed:
        return "FAIL", cases, "no bench timing versus baseline at " + ", ".join(untimed)
    return "PASS", cases, None


def evaluate(workspace: Path, role: str, action: str) -> tuple[str, list, str | None, dict | None]:
    start = read_json(workspace, "start.json")
    # performance always measures afresh: a cached report could be one the agent wrote.
    reports = ensure_report(workspace, role, start, fresh=action == "performance")
    report = json.loads((reports / "report.json").read_text(encoding="utf-8"))
    exit_code = int((reports / "exit_code").read_text())
    return (*judge(action, start, report, exit_code), None)


def pinned(text: str, pattern: re.Pattern, what: str) -> str:
    match = pattern.search(text)
    if not match:
        raise Failed(f"no {what} pin at the SIKL commit")
    return match.group(1)


def installed_version(distribution: str) -> str:
    try:
        return metadata.version(distribution).split("+")[0]
    except metadata.PackageNotFoundError:
        return "not installed"


def validate_task(workspace: Path) -> tuple[str, list, str | None, dict | None]:
    start = read_json(workspace, "start.json")
    provenance = read_json(workspace, "scripts/provenance.json")
    commit = provenance["sikl_commit"]
    missing = [f"source/{s['path']}" for s in start["kernel"]["sources"]
               if not (workspace / "source" / s["path"]).is_file()
               or not (workspace / "source" / s["path"]).stat().st_size]
    if missing:
        raise Failed("candidate source missing or empty: " + ", ".join(missing))
    try:
        git(SIKL_ROOT, "cat-file", "-e", f"{commit}^{{commit}}")
    except subprocess.CalledProcessError:
        raise Failed(f"sikl_commit {commit} not in {SIKL_ROOT}") from None
    listed = git(SIKL_ROOT, "ls-tree", commit, "--", provenance["schema_path"]).split()
    expected = listed[2] if len(listed) > 2 else "none"
    actual = git(SIKL_ROOT, "hash-object", "--no-filters", str(workspace / "start.json")).strip()
    if actual != expected:
        raise Failed(f"start.json oid {actual} != {expected} at {provenance['schema_path']}")
    for distribution, file, pattern in (("triton", ".github/workflows/ci.yaml", TRITON_PIN),
                                        ("flydsl", "setup.py", FLYDSL_PIN)):
        pin = pinned(git(SIKL_ROOT, "show", f"{commit}:{file}"), pattern, distribution)
        version = installed_version(distribution)
        if version != pin:
            raise Failed(f"{distribution} {version} != pin {pin}")
    gitlink = git(SIKL_ROOT, "ls-tree", commit, "--", CK).split()
    expected = gitlink[2] if len(gitlink) > 2 else "none"
    try:
        # An uninitialized submodule directory would resolve to the superproject's HEAD.
        if not (SIKL_ROOT / CK / ".git").exists():
            raise OSError
        actual = git(SIKL_ROOT / CK, "rev-parse", "HEAD").strip()
    except (subprocess.CalledProcessError, OSError):
        raise Failed(f"CK submodule missing: {SIKL_ROOT / CK}") from None
    if actual != expected:
        raise Failed(f"CK submodule {actual} != {expected}")
    for path in (SIKL_ROOT, SIKL_ROOT / ".git", SIKL_ROOT / ".git" / "objects"):
        if os.access(path, os.W_OK):
            raise Failed(f"AKA_SIKL_ROOT {SIKL_ROOT} is writable by this uid")
    cases = [{"test_case_id": i, "status": "PASS", "checks": ["correctness", "performance"]} for i in case_ids(start)]
    return "PASS", cases, None, {"candidate_state": "implemented"}


def failed_cases(workspace: Path, action: str) -> list:
    if action in ("validate-task", "compile"):
        return []
    try:
        return [{"test_case_id": i, "status": "FAIL"} for i in case_ids(read_json(workspace, "start.json"))]
    except Exception:
        return []


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if argv == ["validate-task"]:
        role, action = "task", "validate-task"
    elif len(argv) == 2 and argv[0] in ROLES and argv[1] in ACTIONS:
        role, action = argv
    else:
        print(f"usage: task_runner.py validate-task | {{{','.join(ROLES)}}} {{{','.join(ACTIONS)}}}", file=sys.stderr)
        return 2
    workspace = Path.cwd()
    try:
        if role == "task":
            status, cases, reason, metadata_ = validate_task(workspace)
        else:
            status, cases, reason, metadata_ = evaluate(workspace, role, action)
    except Exception as exc:  # AKA treats a missing result line as a protocol error, not a FAIL
        stderr = getattr(exc, "stderr", None)
        reason = (str(exc) or type(exc).__name__) + (f"\n{tail(stderr)}" if stderr else "")
        status, metadata_ = "FAIL", None
        cases = failed_cases(workspace, action)
    report = {"protocol": "arena-eval-v1", "role": role, "action": action, "status": status, "cases": cases}
    if reason is not None:
        report["reason"] = reason
    if metadata_ is not None:
        report["metadata"] = metadata_
    print("ARENA_EVAL_RESULT=" + json.dumps(report, allow_nan=False, separators=(",", ":")))
    return 0 if status == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
